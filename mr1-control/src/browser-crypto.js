function rotateRight(value, count) {
  return (value >>> count) | (value << (32 - count));
}

function bytesOf(value) {
  if (value instanceof Uint8Array) return value;
  if (value instanceof ArrayBuffer) return new Uint8Array(value);
  if (ArrayBuffer.isView(value)) return new Uint8Array(value.buffer, value.byteOffset, value.byteLength);
  throw new TypeError("SHA-256 input must be bytes.");
}

function pureSha256(value) {
  const source = bytesOf(value);
  const paddedLength = Math.ceil((source.length + 9) / 64) * 64;
  const padded = new Uint8Array(paddedLength);
  padded.set(source);
  padded[source.length] = 0x80;
  const bitLength = BigInt(source.length) * 8n;
  const paddedView = new DataView(padded.buffer);
  paddedView.setUint32(paddedLength - 8, Number((bitLength >> 32n) & 0xffffffffn), false);
  paddedView.setUint32(paddedLength - 4, Number(bitLength & 0xffffffffn), false);

  const hash = new Uint32Array(SHA256_INITIAL);
  const words = new Uint32Array(64);
  for (let offset = 0; offset < paddedLength; offset += 64) {
    for (let index = 0; index < 16; index += 1) {
      words[index] = paddedView.getUint32(offset + (index * 4), false);
    }
    for (let index = 16; index < 64; index += 1) {
      const left = words[index - 15];
      const right = words[index - 2];
      const sigma0 = rotateRight(left, 7) ^ rotateRight(left, 18) ^ (left >>> 3);
      const sigma1 = rotateRight(right, 17) ^ rotateRight(right, 19) ^ (right >>> 10);
      words[index] = (words[index - 16] + sigma0 + words[index - 7] + sigma1) >>> 0;
    }

    let [a, b, c, d, e, f, g, h] = hash;
    for (let index = 0; index < 64; index += 1) {
      const sum1 = rotateRight(e, 6) ^ rotateRight(e, 11) ^ rotateRight(e, 25);
      const choose = (e & f) ^ (~e & g);
      const temp1 = (h + sum1 + choose + SHA256_ROUND[index] + words[index]) >>> 0;
      const sum0 = rotateRight(a, 2) ^ rotateRight(a, 13) ^ rotateRight(a, 22);
      const majority = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (sum0 + majority) >>> 0;
      h = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }
    hash[0] = (hash[0] + a) >>> 0;
    hash[1] = (hash[1] + b) >>> 0;
    hash[2] = (hash[2] + c) >>> 0;
    hash[3] = (hash[3] + d) >>> 0;
    hash[4] = (hash[4] + e) >>> 0;
    hash[5] = (hash[5] + f) >>> 0;
    hash[6] = (hash[6] + g) >>> 0;
    hash[7] = (hash[7] + h) >>> 0;
  }

  const digest = new Uint8Array(32);
  const digestView = new DataView(digest.buffer);
  hash.forEach((word, index) => digestView.setUint32(index * 4, word, false));
  return digest;
}

function hex(bytes) {
  return [...bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("").toUpperCase();
}

export async function sha256BytesHex(value, cryptoProvider = globalThis.crypto) {
  const bytes = bytesOf(value);
  if (cryptoProvider?.subtle?.digest) {
    return hex(new Uint8Array(await cryptoProvider.subtle.digest("SHA-256", bytes)));
  }
  return hex(pureSha256(bytes));
}

export function sha256TextHex(value, cryptoProvider = globalThis.crypto) {
  return sha256BytesHex(new TextEncoder().encode(String(value)), cryptoProvider);
}

export function secureUuidV4(options = {}) {
  const cryptoProvider = options.cryptoProvider ?? globalThis.crypto;
  const randomUuid = options.randomUuid ?? cryptoProvider?.randomUUID?.bind(cryptoProvider);
  if (typeof randomUuid === "function") return String(randomUuid());
  if (typeof cryptoProvider?.getRandomValues !== "function") {
    throw new Error("Secure random ID generation is unavailable.");
  }
  const bytes = new Uint8Array(16);
  cryptoProvider.getRandomValues(bytes);
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const value = hex(bytes).toLowerCase();
  return `${value.slice(0, 8)}-${value.slice(8, 12)}-${value.slice(12, 16)}-${value.slice(16, 20)}-${value.slice(20)}`;
}
